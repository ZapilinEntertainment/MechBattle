    [BurstCompile]
    public static quaternion GetLimitedNormalizedRotation(float2 normalizedRotationLerpValue, float2 limits)
    {
        normalizedRotationLerpValue = math.clamp(normalizedRotationLerpValue, 0f, 1f);
        limits = math.clamp(limits, -1f, 1f);

        // dot with forward is Y coord
        var maxAngleRadianX = math.acos(limits.x);
        var angleRadianX = math.lerp(- maxAngleRadianX, maxAngleRadianX, normalizedRotationLerpValue.x);

        var maxAngleRadianY = math.acos(limits.y);
        var angleRadianY = math.lerp(-maxAngleRadianY, maxAngleRadianY, normalizedRotationLerpValue.y);

       // UnityEngine.Debug.Log($"X: {limits.x} : {math.degrees( - maxAngleRadianX)} -> {math.degrees(maxAngleRadianX)} = {angleRadianX} / {math.degrees(angleRadianX)}");
       // UnityEngine.Debug.Log($"Y: {limits.y} : {math.degrees( - maxAngleRadianY)} -> {math.degrees(maxAngleRadianY)} = {angleRadianY} / {math.degrees(angleRadianY)}");

        Quaternion rotY = Quaternion.AngleAxis(math.degrees(angleRadianY), Vector3.up);
        Quaternion rotX = Quaternion.AngleAxis(math.degrees(angleRadianX), Vector3.right);
        return math.mul(rotY, rotX);
    }


