    [BurstCompile]
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public static quaternion RotateTowards(in quaternion from, in quaternion to, float angleInDegrees)
    {
        var maxAngle = math.angle(from, to) * math.TODEGREES;
        if (maxAngle == 0f)
        {
            return to;
        }

        return math.slerp(from, to, math.min(1f, angleInDegrees / maxAngle));
    }

    [BurstCompile]
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public static float3 MoveTowards(float3 current, float3 target, float maxDelta)
    {
        var dir = target - current;
        var sqlen = math.lengthsq(dir);
        if (sqlen <= maxDelta * maxDelta)
        {
            return target;
        }
        var rlen = math.rsqrt(sqlen);
        return current + dir * rlen * maxDelta;
    }

    [BurstCompile]
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    // generated by Google AI
    public static float MoveTowards(float current, float target, float maxDelta)
    {
        float absMaxDelta = math.abs(maxDelta);
        float clampedDelta = math.clamp(target - current, -absMaxDelta, absMaxDelta);

        return current + clampedDelta;
    }

    // generated by Deepseek, checked by Google AI
    [BurstCompile]
    public static float GetSignedAngleInPlane(float3 from, float3 to, float3 planeNormal)
    {
        float dot = math.dot(from, to);
        float det = math.dot(math.cross(from, to), planeNormal);

        return math.atan2(det, dot); 
    }
