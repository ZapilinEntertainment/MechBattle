    [BurstCompile]
    public static quaternion RotateTowards(quaternion from, quaternion to, float maxAngleDelta)
    {
        float dot = math.clamp(math.dot(from, to), -1f, 1f);
        float angle = math.acos(math.abs(dot)) * 2f;
        if (angle <= maxAngleDelta || angle < math.EPSILON)
        {
            return to;
        }
        float t = maxAngleDelta / angle;
        quaternion target = dot < 0f ? new quaternion(-to.value) : to;

        return math.slerp(from, target, t);
    }

