    [BurstCompile]
    public static quaternion ClampRotation(quaternion q, float2 limits)
    {
        // 1. Извлекаем чистый вектор направления взгляда. 
        float3 forward = math.forward(q);

        // 2. Ограничение PITCH (Вверх / Вниз)
        // limits.x — это косинус максимального угла отклонения от горизонтали (плоскости XZ)
        if (limits.x > -1f)
        {
            // Проекция на вертикальную ось Y не должна превышать синус предельного угла
            // Синус находим через косинус: sin = sqrt(1 - cos^2)
            float maxSinPitch = math.sqrt(1f - limits.x * limits.x);

            // Если текущий Y (синус угла) больше допустимого, зажимаем его
            if (math.abs(forward.y) > maxSinPitch)
            {
                forward.y = math.select(-maxSinPitch, maxSinPitch, forward.y > 0f);

                // Корректируем длину XZ, чтобы общая длина вектора осталась равной 1
                float scaleXZ = math.sqrt(1f - forward.y * forward.y) / (math.length(forward.xz) + 1e-6f);
                forward.x *= scaleXZ;
                forward.z *= scaleXZ;
            }
        }

        // 3. Ограничение YAW (Влево / Вправо)
        // limits.y — это косинус максимального угла отклонения от центральной оси Z
        if (limits.y > -1f)
        {
            // Нормализуем проекцию на плоскость XZ, чтобы проверить чистый поворот влево/вправо
            float lenXZ = math.length(forward.xz);
            if (lenXZ > 1e-6f)
            {
                float3 normXZ = new float3(forward.x, 0f, forward.z) / lenXZ;

                // Вектор normXZ.z — это и есть косинус угла Yaw. Он не должен быть меньше лимита.
                if (normXZ.z < limits.y)
                {
                    // Зажимаем косинус на границе лимита
                    normXZ.z = limits.y;
                    // Рассчитываем новый X (синус) с сохранением исходного знака поворота
                    normXZ.x = math.select(-1f, 1f, forward.x >= 0f) * math.sqrt(1f - limits.y * limits.y);

                    // Возвращаем скорректированную проекцию обратно в forward
                    forward.x = normXZ.x * lenXZ;
                    forward.z = normXZ.z * lenXZ;
                }
            }
        }

        // 4. Собираем кватернион через LookRotation.
        // math.normalize гарантирует, что на входе будет идеальный единичный вектор.
        return quaternion.LookRotation(math.normalize(forward), new float3(0f, 1f, 0f));
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    [BurstCompile]
    public static float2 GetAxisProjectionsFast2D(quaternion q)
    {
        float4 v = q.value;

        return new float2(
            v.w * v.w + v.x * v.x - v.y * v.y - v.z * v.z,  // rawDots.x: Локальный Right · Мировой Right
            v.w * v.w - v.x * v.x + v.y * v.y - v.z * v.z   // rawDots.y: Локальный Up · Мировой Up
        );
    }

    [BurstCompile]
    public static bool IsQuaternionNormalized(quaternion rot) => math.abs(math.lengthsq(rot) - 1.0f) < 0.0001f;

    [BurstCompile]
    public static RigidTransform Lerp(RigidTransform pointA, RigidTransform pointB, float t)
    {
        t = math.clamp(t, 0f, 1f);
        var pos = math.lerp(pointA.pos, pointB.pos, t);
        var rot = math.slerp(pointA.rot, pointB.rot, t);
        return new(rot, pos);
    }

    [BurstCompile]
    public static int UnitsRadiusToTriangular(float radiusInUnits, float triangleHeight) => (int)math.round(radiusInUnits / triangleHeight) + 1;

    [BurstCompile]    
    public static void ComputeAABB(float2 size, float3 position, quaternion rotation, out float3 min, out float3 max)
    {
        // generated by Google AI
        float2 halfSize = size * 0.5f;

        float3 dirX = math.mul(rotation, new float3(1, 0, 0)) * halfSize.x;
        float3 dirZ = math.mul(rotation, new float3(0, 0, 1)) * halfSize.y;
        float3 extents = math.abs(dirX) + math.abs(dirZ);

        min = position - extents;
        max = position + extents;
    }

    [BurstDiscard]
    public static RigidTransform CalculateLocalPointInPointSpace(Transform spaceTransform, Transform calculatingTransform)
    {
        // generated by Deepseek

        float4x4 chassisLocalMatrix = math.mul(
           spaceTransform.worldToLocalMatrix,
           calculatingTransform.localToWorldMatrix
       );

        float3 localPosition = chassisLocalMatrix.c3.xyz;

        quaternion localRotation = quaternion.LookRotation(
            chassisLocalMatrix.c2.xyz,
            chassisLocalMatrix.c1.xyz
        );

        return new(localRotation, localPosition);
    }


