using Unity.Mathematics;
using UnityEditor;
using UnityEngine;
using ZE.MechBattle;

public static class ZoneDrawer
{
    public static void Draw(RigidTransform point, float2 values, BlockZoneMode mode)
    {
        Handles.DrawSolidDisc(point.pos, Vector3.up, 1f);
        switch (mode)
        {
            case BlockZoneMode.Round:
                {
                    Handles.DrawWireDisc(point.pos, Vector3.up, values.x);
                    break;
                }
            case BlockZoneMode.Rect:
                {
                    DrawRect(point, values);
                    break;
                }
        }
    }

    //generated by Deepseek
    public static void DrawRect(RigidTransform center, float2 size)
    {
        float2 half = size * 0.5f;

        // Локальные углы прямоугольника (по часовой стрелке)
        float3 localBL = new float3(-half.x, 0f, -half.y);
        float3 localBR = new float3(half.x, 0f, -half.y);
        float3 localTR = new float3(half.x, 0f, half.y);
        float3 localTL = new float3(-half.x, 0f, half.y);

        // Трансформируем в мировые координаты
        float3 bl = math.transform(center, localBL);
        float3 br = math.transform(center, localBR);
        float3 tr = math.transform(center, localTR);
        float3 tl = math.transform(center, localTL);

        // Конвертация в Vector3 для Handles
        Vector3 vbl = bl;
        Vector3 vbr = br;
        Vector3 vtr = tr;
        Vector3 vtl = tl;

        Handles.color = Color.blue;
        Handles.DrawLine(vbl, vbr);
        Handles.DrawLine(vbr, vtr);
        Handles.DrawLine(vtr, vtl);
        Handles.DrawLine(vtl, vbl);
    }
}
