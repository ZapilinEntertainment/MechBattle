using System.Collections.Generic;
using Scellecs.Morpeh;
using Unity.Mathematics;
using UnityEngine;
using VContainer;
using ZE.MechBattle.Ecs;
using ZE.MechBattle.Navigation;

namespace ZE.MechBattle.Develop
{
    public class HexCaptureStatusDebugDrawer : MonoBehaviour
    {
        [System.Serializable]
        public struct CaptureData
        {
            public int2 HexCoord;
            public int Player;
            public float CaptureProgress;

        }

        [SerializeField] private List<CaptureData> _captureData = new();
        [SerializeField] private float _maxCaptureValueAlpha = 0.5f;

        private Mesh _hexMesh;
        private Material _hexMaterial;
        private MaterialPropertyBlock _props;

        private bool _isReady = false;
        private Filter _hexFilter;
        private INavigationMap _navigationMap;
        private IPlayersList _playersList;
        private Stash<HexComponent> _hexComponents;
        private Stash<HexCaptureStateComponent> _captureStates;

        private readonly List<HexDrawData> _drawData = new();

        private readonly struct HexDrawData
        {
            public readonly Vector3 WorldPos;
            public readonly Color Color;

            public HexDrawData(Vector3 worldPos, Color color)
            {
                WorldPos = worldPos;
                Color = color;
            }
        }

        [Inject]
        public void Inject(World world, INavigationMap map, IPlayersList playersList)
        {
            _hexFilter = world.Filter.With<HexComponent>().With<HexCaptureStateComponent>().Build();
            _navigationMap = map;
            _playersList = playersList;

            _hexComponents = world.GetStash<HexComponent>();
            _captureStates = world.GetStash<HexCaptureStateComponent>();

            _hexMesh = CreateHexMesh(_navigationMap.HexEdgeLength);
            _hexMaterial = new Material(Shader.Find("Sprites/Default"));
            _props = new MaterialPropertyBlock();

            _isReady = true;
        }

        private void Update()
        {
            if (!_isReady || _hexFilter.IsEmpty())
                return;

            _drawData.Clear();
            _captureData.Clear();

            foreach (var hexEntity in _hexFilter)
            {
                var hexCoord = _hexComponents.Get(hexEntity).Coord;
                var worldPos = HexMath.HexToWorld(hexCoord, _navigationMap.HexEdgeLength);
                var captureState = _captureStates.Get(hexEntity);

                _captureData.Add(new() { HexCoord = hexCoord, Player = captureState.ControllingPlayerId, CaptureProgress = captureState.CaptureProgress});

                if (captureState.ControllingPlayerId == -1)
                    continue;

                var playerColor = _playersList.GetPlayerColor(new PlayerKey(captureState.ControllingPlayerId));
                playerColor.a = captureState.CaptureProgress * _maxCaptureValueAlpha;
                _drawData.Add(new(new Vector3(worldPos.x, 0.01f, worldPos.y), playerColor));
            }

            Draw();
        }

        private void Draw()
        {
            foreach (var drawData in _drawData)
            {
                _props.SetColor("_Color", drawData.Color); 
                Graphics.DrawMesh(_hexMesh, drawData.WorldPos, Quaternion.identity,
                                  _hexMaterial, 0, null, 0, _props);
            }
        }

        // generated by Deepseek
        private static Mesh CreateHexMesh(float radius)
        {
            var mesh = new Mesh();
            var verts = new Vector3[7];
            verts[0] = Vector3.zero;
            for (int i = 0; i < 6; i++)
            {
                float angle = 60f * i * Mathf.Deg2Rad;
                verts[i + 1] = new Vector3(Mathf.Cos(angle) * radius, 0, Mathf.Sin(angle) * radius);
            }
            var tris = new int[18];
            for (int i = 0; i < 6; i++)
            {
                tris[i * 3] = (i + 1) % 6 + 1;
                tris[i * 3 + 1] = i + 1;
                tris[i * 3 + 2] = 0;
            }
            mesh.vertices = verts;
            mesh.triangles = tris;
            mesh.RecalculateNormals();
            return mesh;
        }
    }
}
