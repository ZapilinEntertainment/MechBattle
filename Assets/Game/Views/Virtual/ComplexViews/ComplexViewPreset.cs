using System.Collections.Generic;
using Unity.Mathematics;
using ZE.MechBattle.Ecs;
using ZE.MechBattle.Views;

namespace ZE.MechBattle
{
    public class ComplexViewPreset
    {
        public struct SortedViewPartData
        {
            public ViewPartKey PartKey;
            public ViewPartKey ParentKey;
            public int ParentIndex;            
            public VirtualViewComponent ViewData;
            public float3 LocalPosition;
            public quaternion LocalRotation;
        }

        public readonly SortedViewPartData[] SortedData;
        private readonly VirtualViewApplier _viewApplier;

        public ComplexViewPreset(ComplexVirtualViewConfigurationObject config, VirtualViewApplier virtualViewApplier)
        {
            _viewApplier = virtualViewApplier;

            var length = config.ViewPartsData.Length;
            var itemsCopy = new ComplexVirtualViewConfigurationObject.CompositeObjectViewPartData[length];
            config.ViewPartsData.CopyTo(itemsCopy, 0);
            SortedData = SortByHierarchy(itemsCopy);

            // additional check
            for (var i = 0; i < length; i++)
            {
                if (SortedData[i].ParentKey.Type == ViewPartType.Undefined)
                    continue;

                var parentIndex = SortedData[i].ParentIndex;
                if (parentIndex < 0 || parentIndex >= length)
                {
                    UnityEngine.Debug.LogError("failed to set parent index");
                    SortedData[i].ParentKey = ViewPartKey.Undefined;
                }
            }
        }


        // generated by GoogleAI
        // arrange elements in hierarchy order (children will be created after parents)
        public SortedViewPartData[] SortByHierarchy(ComplexVirtualViewConfigurationObject.CompositeObjectViewPartData[] items)
        {
            if (items == null)
                return null;

            var result = new SortedViewPartData[items.Length];
            if (items.Length == 0)
                return result;

            // 1. Заполняем целевой массив преобразованными элементами
            for (int i = 0; i < items.Length; i++)
            {
                result[i] = ToSortedData(items[i], -1);
            }

            var comparer = EqualityComparer<ViewPartKey>.Default;

            // 2. Сортируем выходной массив на месте и проставляем ParentIndex
            int current = 0;
            while (current < result.Length)
            {
                var currentParentKey = result[current].ParentKey;
                bool swapped = false;

                for (int j = current + 1; j < result.Length; j++)
                {
                    if (comparer.Equals(result[j].PartKey, currentParentKey))
                    {
                        (result[current], result[j]) = (result[j], result[current]);
                        swapped = true;
                        break;
                    }
                }

                if (!swapped)
                {
                    int parentIdx = -1;
                    for (int k = 0; k < current; k++)
                    {
                        if (comparer.Equals(result[k].PartKey, currentParentKey))
                        {
                            parentIdx = k;
                            break;
                        }
                    }

                    result[current].ParentIndex = parentIdx;
                    current++;
                }
            }

            return result;
        }

        private SortedViewPartData ToSortedData(ComplexVirtualViewConfigurationObject.CompositeObjectViewPartData element, int parentIndex) => new()
        {
            PartKey = element.PartKey,
            ParentKey = element.ParentKey,
            ParentIndex = -1,
            ViewData = _viewApplier.ConfigToComponent( element.ViewData),
            LocalPosition = element.ViewData.Position,
            LocalRotation = element.ViewData.Rotation
        };
    }
}
