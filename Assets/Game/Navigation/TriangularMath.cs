            bool3 mask = (isEqual & isPeak) | (!isEqual & isGreater);
            int3 maskInt = math.select(new int3(0), new int3(4, 2, 1), mask);
            int index = maskInt.x + maskInt.y + maskInt.z;

            //return index switch
