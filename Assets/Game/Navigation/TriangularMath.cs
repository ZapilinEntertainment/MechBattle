        [BurstCompile]
        public static HexSector DefineSector(IntTriangularPos pos, float hexEdgeLength, int hexRadius, float triangleHeight)
        {
            var hexCoord = TriangularMath.TriangularToHex(pos, triangleHeight, hexEdgeLength);
