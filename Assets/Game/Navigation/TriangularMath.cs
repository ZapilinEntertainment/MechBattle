        public static readonly float3 DirY = new float3(0,0f,1f);
        public static readonly float3 DirZ = math.normalize( math.mul(quaternion.AxisAngle(math.up(), math.radians(120f)), math.forward()));
        public static readonly float3 DirX = math.normalize( math.mul(quaternion.AxisAngle(math.down(), math.radians(120f)), math.forward()));

        private const float FACTOR = 2f / 3f;

        [BurstCompile]
        public static IntTriangularPos DoOffsetAlongEdge(IntTriangularPos start, HexEdge edge, int offset)
        {
            var half = offset / 2;
            var otherHalf = offset - half;
            var peakDirection = edge.ToAlongsidePeakDirection().ToTriangularOffsetVector();
            var valleyDirection = edge.ToAlongsideValleyDirection().ToTriangularOffsetVector();

            return start + (start.IsPeak 
                ? (half * peakDirection + otherHalf * valleyDirection)
                : (half * valleyDirection + otherHalf * peakDirection));
        }

        [BurstCompile]
        public static IntTriangularPos GetPeakNeighbour(IntTriangularPos pos, PeakNeighbour peakNeighbour, int offset = 1) => 
            pos + peakNeighbour.ToTriangularOffsetVector();

