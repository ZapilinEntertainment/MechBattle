        public static IntTriangularPos GetPeakNeighbour(IntTriangularPos pos, int peakNeighbour) => 
            GetPeakNeighbour(pos, (PeakNeighbour)peakNeighbour);

        // generated by Google AI based on GetPeakNeighbour()
        [BurstCompile]
        public static PeakNeighbour DefinePeakNeighbour(IntTriangularPos origin, IntTriangularPos target)
        {
            int dDL = target.DownLeft - origin.DownLeft;
            int dUp = target.Up - origin.Up;
            int dDR = target.DownRight - origin.DownRight;

            return (dDL, dUp, dDR) switch
            {
                (-1, 1, 0) => PeakNeighbour.VertexUpRight,
                (0, 1, 1) => PeakNeighbour.EdgeUpRight,
                (-1, 0, 1) => PeakNeighbour.VertexRight,
                (0, 0, 2) => PeakNeighbour.VertexDownRightValley,
                (0, -1, 1) => PeakNeighbour.VertexDownRightPeak,
                (1, 0, 1) => PeakNeighbour.EdgeDown,
                (1, -1, 0) => PeakNeighbour.VertexDownLeftPeak,
                (2, 0, 0) => PeakNeighbour.VertexDownLeftValley,
                (1, 0, -1) => PeakNeighbour.VertexLeft,
                (1, 1, 0) => PeakNeighbour.EdgeUpLeft,
                (0, 1, -1) => PeakNeighbour.VertexUpLeft,
                _ => PeakNeighbour.VertexUp //
            };
        }

        [BurstCompile]
        public static IntTriangularPos GetValleyNeighbour(IntTriangularPos pos, ValleyNeighbour valleyNeighbour) => 
            pos + valleyNeighbour.ToTriangularOffsetVector();

        [BurstCompile]
        public static IntTriangularPos GetValleyNeighbour(IntTriangularPos pos, int valleyNeighbour) => GetValleyNeighbour(pos, (ValleyNeighbour)valleyNeighbour);

        // generated by Google AI based on GetValleyNeighbour()
        [BurstCompile]
        public static ValleyNeighbour DefineValleyNeighbour(IntTriangularPos origin, IntTriangularPos target)
        {
            int dDL = target.DownLeft - origin.DownLeft;
            int dUp = target.Up - origin.Up;
            int dDR = target.DownRight - origin.DownRight;

            return (dDL, dUp, dDR) switch
            {
                (-1, 1, 0) => ValleyNeighbour.VertexUpRightValley,
                (-2, 0, 0) => ValleyNeighbour.VertexUpRightPeak,
                (-1, 0, 1) => ValleyNeighbour.VertexRight,
                (-1, -1, 0) => ValleyNeighbour.EdgeDownRight,
                (0, -1, 1) => ValleyNeighbour.VertexDownRight,
                (0, -2, 0) => ValleyNeighbour.VertexDown,
                (1, -1, 0) => ValleyNeighbour.VertexDownLeft,
                (0, -1, -1) => ValleyNeighbour.EdgeDownLeft,
                (1, 0, -1) => ValleyNeighbour.VertexLeft,
                (0, 0, -2) => ValleyNeighbour.VertexUpLeftPeak,
                (0, 1, -1) => ValleyNeighbour.VertexUpLeftValley,
                _ => ValleyNeighbour.EdgeUp 
            };
        }


