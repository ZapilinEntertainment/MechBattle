        public static int CalculateHexPosDistance(int2 hexPosA, int2 hexPosB)
        {
            int x1 = hexPosA.x;
            int z1 = hexPosA.y;
            int y1 = -x1 - z1;

            int x2 = hexPosB.x;
            int z2 = hexPosB.y;
            int y2 = -x2 - z2;

            return math.max(
                math.abs(x1 - x2),
                math.max(
